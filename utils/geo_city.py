CRIMEA_BBOX = (44.0, 46.5, 32.0, 37.0)


def detect_city_by_coords(lat: float | None, lon: float | None) -> str:
    """Вернуть название города или '' если координаты вне известных bboxes."""
    if lat is None or lon is None:
        return ""
    lat = float(lat)
    lon = float(lon)
    for name, lat_min, lat_max, lon_min, lon_max in CITY_BBOXES:
        if lat_min <= lat <= lat_max and lon_min <= lon <= lon_max:
            return name
    c_lat_min, c_lat_max, c_lon_min, c_lon_max = CRIMEA_BBOX
    if c_lat_min <= lat <= c_lat_max and c_lon_min <= lon <= c_lon_max:
        return "Крым"
    return ""
